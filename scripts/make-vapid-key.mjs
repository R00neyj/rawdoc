// VAPID 비밀 JWK 한 줄을 stdout 에, 안내는 stderr 에 (specs/features/F-3003.md 6.5)
const pair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign'])
const { kty, crv, d, x, y } = await crypto.subtle.exportKey('jwk', pair.privateKey)
const raw = new Uint8Array(await crypto.subtle.exportKey('raw', pair.publicKey))
const publicKey = Buffer.from(raw).toString('base64url')
process.stdout.write(`${JSON.stringify({ kty, crv, d, x, y })}\n`)
process.stderr.write(`${publicKey}\n`)
process.stderr.write('npx wrangler secret put VAPID_PRIVATE_JWK 에 위 한 줄을 붙여 넣으세요.\n')
process.stderr.write('이 값을 잃거나 바꾸면 모든 기기가 다시 구독해야 합니다. 저장소에 커밋하지 마세요.\n')
